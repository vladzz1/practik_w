import matplotlib.pyplot as plt  # Імпортуємо модуль pyplot для побудови графіків
import numpy as np               # Імпортуємо бібліотеку NumPy

# Фіксуємо початкове значення генератора випадкових чисел
# Це потрібно, щоб при кожному запуску отримувати однакові дані
np.random.seed(42)

# Створюємо масив із 100 випадкових чисел
data1 = np.random.randn(100)

# Створюємо масив індексів від 0 до 99 для осі X
xdata = np.arange(len(data1))

# Створюємо фігуру з двома графіками, розташованими один під одним
fig, axs = plt.subplots(2, 1, layout='constrained')

# Будуємо перший графік
axs[0].plot(xdata, data1)

# Додаємо заголовок першого графіка
axs[0].set_title('Автоматичні поділки')

# Будуємо другий графік
axs[1].plot(xdata, data1)

# Встановлюємо власні поділки осі X
axs[1].set_xticks(
    np.arange(0, 100, 30),
    ['нуль', '30', 'шістдесят', '90']
)

# Встановлюємо власні поділки осі Y
axs[1].set_yticks([-1.5, 0, 1.5])

# Додаємо заголовок другого графіка
axs[1].set_title('Ручне налаштування поділок')

# Додаємо підписи осей
axs[0].set_xlabel('Номер елемента')
axs[0].set_ylabel('Значення')

axs[1].set_xlabel('Номер елемента')
axs[1].set_ylabel('Значення')

# Відображаємо сітку
axs[0].grid(True)
axs[1].grid(True)

# Відображаємо графіки
plt.show()