import matplotlib.pyplot as plt  # Імпортуємо модуль pyplot для побудови графіків
import numpy as np               # Імпортуємо бібліотеку NumPy для роботи з масивами

# Створюємо фігуру (Figure) та область побудови графіка (Axes)
# figsize=(5, 2.7) задає розмір фігури у дюймах
fig, ax = plt.subplots(figsize=(5, 2.7))

# Створюємо масив значень від 0 до 5 з кроком 0.01
t = np.arange(0.0, 5.0, 0.01)

# Обчислюємо значення функції y = cos(2πt)
s = np.cos(2 * np.pi * t)

# Будуємо графік косинуса
# lw=2 означає товщину лінії 2 пікселі
line, = ax.plot(t, s, lw=2)

# Додаємо анотацію до локального максимуму графіка
# xy=(2, 1) — точка, на яку вказує стрілка
# xytext=(3, 1.5) — місце розташування тексту
# arrowprops — параметри стрілки
ax.annotate(
    'Локальний максимум',
    xy=(2, 1),
    xytext=(3, 1.5),
    arrowprops=dict(
        facecolor='black',  # Колір стрілки
        shrink=0.05          # Скорочення довжини стрілки на 5%
    )
)

# Встановлюємо межі осі Y від -2 до 2
ax.set_ylim(-2, 2)

# Додаємо підпис осі X
ax.set_xlabel('Час')

# Додаємо підпис осі Y
ax.set_ylabel('Значення cos(t)')

# Додаємо заголовок графіка
ax.set_title('Графік функції косинуса')

# Відображаємо сітку
ax.grid(True)

# Відображаємо графік
plt.show()